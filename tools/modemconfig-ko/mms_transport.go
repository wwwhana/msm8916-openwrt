type mmsCarrier struct {
	mmsc, proxy string
}

// AOSP device/sample/etc/apns-full-conf.xml: MMS uses the data APN on all
// three Korean LTE profiles, separately from the IMS bearer on wwan1.
func koreanMMSCarrier(plmn string) (mmsCarrier, error) {
	switch plmn {
	case "45005":
		return mmsCarrier{"http://omms.nate.com:9082/oma_mms", "http://smart.nate.com:9093"}, nil
	case "45006":
		return mmsCarrier{"http://omammsc.uplus.co.kr:9084", ""}, nil
	case "45008":
		return mmsCarrier{"http://mmsc.ktfwing.com:9082", ""}, nil
	}
	return mmsCarrier{}, errors.New("unsupported MMS carrier")
}

func (carrier mmsCarrier) validateLocation(value string) error {
	location, err := url.Parse(value)
	base, baseErr := url.Parse(carrier.mmsc)
	if err != nil || baseErr != nil || len(value) > 2048 || location.User != nil || location.Fragment != "" || location.Opaque != "" || location.Hostname() != base.Hostname() || (location.Scheme != "http" && location.Scheme != "https") {
		return errors.New("invalid MMS location")
	}
	port := location.Port()
	if port != "" && port != base.Port() && !(base.Hostname() == "omammsc.uplus.co.kr" && port == "9095") && port != "443" {
		return errors.New("invalid MMS port")
	}
	return nil
}

func mmsHTTPClient(carrier mmsCarrier) (*http.Client, error) {
	dialer := &net.Dialer{Timeout: 15 * time.Second, Control: func(_, _ string, raw syscall.RawConn) error {
		var bindErr error
		err := raw.Control(func(fd uintptr) { bindErr = unix.BindToDevice(int(fd), "wwan0") })
		if err != nil {
			return err
		}
		return bindErr
	}}
	transport := &http.Transport{DialContext: dialer.DialContext, DisableKeepAlives: true, ResponseHeaderTimeout: 20 * time.Second, MaxResponseHeaderBytes: 64 << 10}
	if carrier.proxy != "" {
		proxy, err := url.Parse(carrier.proxy)
		if err != nil {
			return nil, errors.New("invalid MMS proxy")
		}
		transport.Proxy = http.ProxyURL(proxy)
	}
	return &http.Client{Transport: transport, Timeout: 45 * time.Second, CheckRedirect: func(request *http.Request, via []*http.Request) error {
		if len(via) >= 3 || carrier.validateLocation(request.URL.String()) != nil {
			return errors.New("MMS redirect refused")
		}
		return nil
	}}, nil
}

// Only fixed error codes escape this layer: URL paths can identify a message.
func mmsRequest(ctx context.Context, client *http.Client, method, location string, data []byte) ([]byte, error) {
	request, err := http.NewRequestWithContext(ctx, method, location, bytes.NewReader(data))
	if err != nil {
		return nil, errors.New("mms-network")
	}
	request.Header.Set("Accept", "application/vnd.wap.mms-message")
	request.Header.Set("User-Agent", "ModemConfig-KO/1.0")
	if method == http.MethodPost {
		request.Header.Set("Content-Type", "application/vnd.wap.mms-message")
	}
	response, err := client.Do(request)
	if err != nil {
		return nil, errors.New("mms-network")
	}
	defer response.Body.Close()
	if response.StatusCode < 200 || response.StatusCode >= 300 {
		return nil, errors.New("mms-http-" + strconv.Itoa(response.StatusCode))
	}
	if response.ContentLength > maxMMSBytes {
		return nil, errors.New("mms-too-large")
	}
	result, err := io.ReadAll(io.LimitReader(response.Body, maxMMSBytes+1))
	if err != nil {
		return nil, errors.New("mms-network")
	}
	if len(result) > maxMMSBytes {
		return nil, errors.New("mms-too-large")
	}
	return result, nil
}

func mmsNotifyResponse(transaction, version string) ([]byte, error) {
	if transaction == "" || len(transaction) > 256 || strings.ContainsRune(transaction, 0) {
		return nil, errors.New("invalid MMS transaction")
	}
	v := byte(0x90)
	switch version {
	case "1.1":
		v = 0x91
	case "1.2":
		v = 0x92
	case "1.3":
		v = 0x93
	}
	data := append([]byte{0x8c, 0x83, 0x98}, []byte(transaction)...)
	// Retrieved is sent only after both raw PDU and decoded parts are durable.
	// No read report is generated by downloading or opening a conversation.
	return append(data, 0, 0x8d, v, 0x95, 0x81, 0x91, 0x81), nil
}

func (db *messageDB) processMMS(ctx context.Context, carrier mmsCarrier, client *http.Client, verify func(context.Context) error) error {
	cutoff := time.Now().Add(-time.Minute).UTC().Format(databaseTime)
	rows, err := db.run(`SELECT m.id,a.id AS attempt,a.state,n.transaction_id,n.mms_version,n.content_location,n.expires_at,n.message_size
        FROM transport_attempts a JOIN messages m ON m.id=a.message_id
        JOIN conversations c ON c.id=m.conversation_id JOIN mms_metadata n ON n.message_id=m.id
        WHERE c.subscription_id=`+sqlText(db.subscription)+` AND a.protocol='mms' AND m.direction='incoming'
        AND (a.state IN('mms_waiting','mms_ack_pending') OR
             (a.state IN('mms_download_failed','mms_ack_failed') AND a.updated_at<`+sqlText(cutoff)+`))
        ORDER BY a.updated_at,a.id LIMIT 1;`, true)
	if err != nil || len(rows) == 0 {
		return err
	}
	row := rows[0]
	message, attempt, state := row["id"].(string), int64(row["attempt"].(float64)), row["state"].(string)
	if err := verify(ctx); err != nil {
		return err
	}
	fail := func(state, code string) error {
		_, err := db.run("UPDATE transport_attempts SET state="+sqlText(state)+",failure_reason="+sqlText(code)+",updated_at="+sqlText(timestamp())+" WHERE id="+strconv.FormatInt(attempt, 10)+";", false)
		emit(map[string]any{"stage": "mms-receive", "state": state, "reason": code})
		return err
	}
	if state == "mms_waiting" || state == "mms_download_failed" {
		location := row["content_location"].(string)
		if carrier.validateLocation(location) != nil {
			return fail("mms_unavailable", "mms-location")
		}
		original, err := db.run("SELECT hex(payload) AS data FROM mms_pdus WHERE message_id="+sqlText(message)+" AND message_type='m-retrieve-conf' AND direction='incoming' ORDER BY occurred_at DESC LIMIT 1;", true)
		if err != nil {
			return err
		}
		var data []byte
		if len(original) > 0 {
			data, err = hex.DecodeString(original[0]["data"].(string))
			if err != nil {
				return err
			}
			if pdu, err := decodeMMS(data, time.Now()); err == nil && pdu.kind == 0x84 && pdu.retrieveStatus >= 0xc0 && pdu.retrieveStatus < 0xe0 {
				// Retain the error PDU for diagnosis, but a transient server
				// error is not the message content to reuse on the next try.
				data = nil
			}
		}
		if expiry, _ := row["expires_at"].(string); expiry != "" && len(data) == 0 {
			end, err := time.Parse(databaseTime, expiry)
			if err != nil || !time.Now().Before(end) {
				return fail("mms_expired", "mms-expired")
			}
		}
		if row["message_size"].(float64) > maxMMSBytes {
			return fail("mms_unavailable", "mms-too-large")
		}
		claimed, err := db.run("UPDATE transport_attempts SET state='mms_downloading',updated_at="+sqlText(timestamp())+" WHERE id="+strconv.FormatInt(attempt, 10)+" AND state IN('mms_waiting','mms_download_failed') RETURNING id;", true)
		if err != nil || len(claimed) == 0 {
			return err
		}
		if len(data) == 0 {
			data, err = mmsRequest(ctx, client, http.MethodGet, location, nil)
			if err != nil {
				return fail("mms_download_failed", err.Error())
			}
			if _, err := db.run(db.mmsPDUSQL(message, row["transaction_id"].(string), "m-retrieve-conf", "incoming", data), false); err != nil {
				return err
			}
		}
		pdu, err := decodeMMS(data, time.Now())
		if err == nil && pdu.kind == 0x84 && pdu.retrieveStatus != 0 && pdu.retrieveStatus != 128 {
			if _, err := db.run("UPDATE mms_metadata SET retrieve_status="+strconv.Itoa(int(pdu.retrieveStatus))+" WHERE message_id="+sqlText(message)+";", false); err != nil {
				return err
			}
			state := "mms_unavailable"
			if pdu.retrieveStatus >= 0xc0 && pdu.retrieveStatus < 0xe0 {
				state = "mms_download_failed"
			}
			return fail(state, "mms-status-"+strconv.Itoa(int(pdu.retrieveStatus)))
		}
		if err != nil || pdu.kind != 0x84 || (pdu.retrieveStatus != 0 && pdu.retrieveStatus != 128) || len(pdu.parts) == 0 {
			return fail("mms_download_failed", "mms-decode")
		}
		if err := verify(ctx); err != nil {
			_ = fail("mms_download_failed", "sim-unavailable")
			return err
		}
		if err := db.saveMMS(message, attempt, data, pdu); err != nil {
			return err
		}
		emit(map[string]any{"stage": "mms-receive", "state": "stored", "parts": len(pdu.parts)})
	}
	if err := verify(ctx); err != nil {
		return err
	}
	claimed, err := db.run("UPDATE transport_attempts SET state='mms_acknowledging',updated_at="+sqlText(timestamp())+" WHERE id="+strconv.FormatInt(attempt, 10)+" AND state IN('mms_ack_pending','mms_ack_failed') RETURNING id;", true)
	if err != nil || len(claimed) == 0 {
		return err
	}
	ack, err := mmsNotifyResponse(row["transaction_id"].(string), row["mms_version"].(string))
	if err != nil {
		return fail("mms_ack_failed", "mms-transaction")
	}
	if _, err := mmsRequest(ctx, client, http.MethodPost, carrier.mmsc, ack); err != nil {
		return fail("mms_ack_failed", err.Error())
	}
	_, err = db.run("BEGIN IMMEDIATE;"+db.mmsPDUSQL(message, row["transaction_id"].(string), "m-notifyresp-ind", "outgoing", ack)+
		"UPDATE transport_attempts SET state='mms_received',failure_reason=NULL,updated_at="+sqlText(timestamp())+" WHERE id="+strconv.FormatInt(attempt, 10)+"; COMMIT;", false)
	return err
}

func runMMSQueue(ctx context.Context, db *messageDB, plmn, session string, verify func(context.Context) error) error {
	carrier, err := koreanMMSCarrier(plmn)
	if err != nil {
		return nil
	}
	client, err := mmsHTTPClient(carrier)
	if err != nil {
		return err
	}
	defer client.CloseIdleConnections()
	_, err = db.run("UPDATE transport_attempts SET state=CASE state WHEN 'mms_downloading' THEN 'mms_waiting' ELSE 'mms_ack_pending' END WHERE state IN('mms_downloading','mms_acknowledging') AND message_id IN(SELECT m.id FROM messages m JOIN conversations c ON c.id=m.conversation_id WHERE c.subscription_id="+sqlText(db.subscription)+");", false)
	if err != nil {
		return err
	}
	ticker := time.NewTicker(3 * time.Second)
	defer ticker.Stop()
	for {
		if err := db.sendMMS(ctx, session, carrier, client, verify); err != nil {
			return err
		}
		if err := db.processMMS(ctx, carrier, client, verify); err != nil {
			return err
		}
		select {
		case <-ctx.Done():
			return nil
		case <-ticker.C:
		}
	}
}
